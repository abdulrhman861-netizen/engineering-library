-- الحسابات والمحاسب ومنفذ POS v4.4
alter table users drop constraint if exists users_role_check;
alter table users add constraint users_role_check check (role in ('ADMIN','ACCOUNTANT','STAFF','TYPIST'));

create table if not exists financial_entries (
  entry_id bigint generated by default as identity primary key,
  entry_date date not null default current_date,
  entry_type text not null check(entry_type in ('INCOME','EXPENSE')),
  category text not null check(category in ('SALES','SALARY','RENT','ELECTRICITY','POS_COMMISSION','SUPPLIES','OTHER')),
  description text,
  amount numeric(14,2) not null check(amount >= 0),
  payment_method text not null default 'CASH' check(payment_method in ('CASH','GREEN_CARD','BLACK_CARD','BANK')),
  created_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists financial_entries_date_idx on financial_entries(entry_date);

create table if not exists pos_transactions (
  pos_id bigint generated by default as identity primary key,
  transaction_date date not null default current_date,
  card_type text not null check(card_type in ('GREEN_CARD','BLACK_CARD')),
  direction text not null default 'IN' check(direction in ('IN','OUT')),
  transfer_amount numeric(14,2) not null check(transfer_amount >= 0),
  commission numeric(14,2) not null default 0 check(commission >= 0),
  notes text,
  created_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists pos_transactions_date_idx on pos_transactions(transaction_date);

create table if not exists partners (
  partner_id bigint generated by default as identity primary key,
  partner_name text not null,
  share_percent numeric(5,2) not null check(share_percent > 0 and share_percent <= 100),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table financial_entries enable row level security;
alter table pos_transactions enable row level security;
alter table partners enable row level security;
