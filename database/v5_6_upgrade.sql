-- تحديث 5.6: إدارة الطباعة الجماعية ومرفقات المهام
alter table if exists student_print_files add column if not exists paper_size text not null default 'A4';
alter table if exists student_print_files drop constraint if exists student_print_files_paper_size_check;
alter table if exists student_print_files add constraint student_print_files_paper_size_check check(paper_size in ('A4','A3'));
alter table if exists student_print_files add column if not exists duplex_mode text not null default 'SIMPLEX';
alter table if exists student_print_files drop constraint if exists student_print_files_duplex_mode_check;
alter table if exists student_print_files add constraint student_print_files_duplex_mode_check check(duplex_mode in ('SIMPLEX','DUPLEX_LONG','DUPLEX_SHORT'));
alter table if exists student_print_files add column if not exists cancelled_by bigint references users(user_id) on delete set null;
alter table if exists student_print_files add column if not exists cancelled_at timestamptz;
alter table if exists student_print_files add column if not exists third_file_path text;
alter table if exists student_print_files add column if not exists third_storage_path text;

create table if not exists print_job_events(
  event_id bigint generated by default as identity primary key,
  file_id bigint references student_print_files(file_id) on delete cascade,
  action text not null,
  from_printer integer,
  to_printer integer,
  details jsonb not null default '{}'::jsonb,
  performed_by bigint references users(user_id) on delete set null,
  agent_id text,
  created_at timestamptz not null default now()
);
create index if not exists print_job_events_file_idx on print_job_events(file_id,created_at);

create table if not exists task_attachments(
  attachment_id bigint generated by default as identity primary key,
  task_id bigint not null references tasks(task_id) on delete cascade,
  original_name text not null,
  file_path text not null,
  storage_path text,
  mime_type text,
  file_size_bytes bigint not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists task_attachments_task_idx on task_attachments(task_id,attachment_id);
alter table if exists student_print_files add column if not exists source_task_attachment_id bigint references task_attachments(attachment_id) on delete set null;
drop index if exists student_print_files_source_task_idx;
create unique index if not exists student_print_files_source_task_attachment_idx on student_print_files(source_task_id,source_task_attachment_id) where source_task_id is not null and source_task_attachment_id is not null;

insert into task_attachments(task_id,original_name,file_path,storage_path)
select task_id,coalesce(attachment_name,title),attachment_path,attachment_storage_path from tasks t
where attachment_path is not null and not exists(select 1 from task_attachments a where a.task_id=t.task_id and a.file_path=t.attachment_path);

