-- نفذ هذا الملف مرة واحدة في Supabase SQL Editor قبل نشر الإصدار 5.5
alter table if exists study_materials add column if not exists page_count integer;
alter table if exists student_print_files add column if not exists page_count integer;

create table if not exists print_history(
  print_id bigint generated by default as identity primary key,
  file_id bigint references student_print_files(file_id) on delete set null,
  printer_number integer not null,
  color_mode text not null check(color_mode in ('BW','COLOR')),
  page_count integer not null default 1,
  copies integer not null default 1,
  total_pages integer not null default 1,
  agent_id text,
  printed_at timestamptz not null default now()
);
create index if not exists print_history_date_idx on print_history(printed_at);
