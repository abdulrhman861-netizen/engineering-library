update departments
set is_active=false
where trim(name)='هندسة العمارة'
  and code <> 'architecture';

alter table if exists student_print_files
  add column if not exists source_material_id bigint references study_materials(material_id) on delete set null;
alter table if exists student_print_files add column if not exists doctor_name text;

update student_print_files f
set source_material_id=case when e.details->>'materialId' ~ '^[0-9]+$' then (e.details->>'materialId')::bigint else f.source_material_id end,
    doctor_name=coalesce(nullif(e.details->>'doctorName',''),f.doctor_name)
from (
  select distinct on (file_id) file_id,details
  from print_job_events
  where action in ('MATERIAL_REQUESTED','MATERIAL_DIRECT_QUEUED')
  order by file_id,created_at desc
) e
where f.file_id=e.file_id;

alter table if exists financial_entries add column if not exists updated_at timestamptz;
alter table if exists financial_entries add column if not exists updated_by bigint references users(user_id) on delete set null;
alter table if exists financial_entries add column if not exists deleted_at timestamptz;
alter table if exists financial_entries add column if not exists deleted_by bigint references users(user_id) on delete set null;

create table if not exists financial_entry_audit (
  audit_id bigint generated by default as identity primary key,
  entry_id bigint,
  action text not null check(action in ('UPDATE','DELETE')),
  old_values jsonb,
  new_values jsonb,
  changed_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists financial_entries_active_date_idx
  on financial_entries(entry_date desc) where deleted_at is null;
alter table financial_entry_audit enable row level security;
