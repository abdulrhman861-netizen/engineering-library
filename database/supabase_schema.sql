-- مكتبة كلية الهندسة الرقمية - الجامعة العراقية
-- نفّذ هذا الملف مرة واحدة في Supabase > SQL Editor
create extension if not exists pgcrypto;

create table if not exists users (
  user_id bigint generated by default as identity primary key,
  full_name text not null,
  username text unique not null,
  password_hash text not null,
  role text not null default 'STAFF' check (role in ('ADMIN','STAFF','TYPIST')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists departments (
  department_id bigint generated by default as identity primary key,
  code text unique not null,
  name text unique not null,
  icon text default 'fa-graduation-cap',
  sort_order integer not null default 0,
  is_active boolean not null default true
);

insert into departments(code,name,icon,sort_order) values
