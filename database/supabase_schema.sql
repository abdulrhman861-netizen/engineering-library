create table if not exists discussions (
  discussion_id bigint generated by default as identity primary key,
  gender text not null check(gender in ('MALE','FEMALE')),
  degree_type text not null check(degree_type in ('MASTER','DOCTORATE')),
  student_name text not null, thesis_title text not null,
  discussion_date text not null, location_hall text not null,
  university_name text, college_name text, template_path text,
  created_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists discussion_committee (
  committee_id bigint generated by default as identity primary key,
  discussion_id bigint not null references discussions(discussion_id) on delete cascade,
  member_name text not null, academic_title text, workplace text,
  role_in_committee text not null, member_order integer not null
);

create table if not exists attendance (
  attendance_id bigint generated by default as identity primary key,
  user_id bigint not null references users(user_id) on delete cascade,
  check_in timestamptz not null default now(), check_out timestamptz,
  regular_hours numeric(6,2) default 0, overtime_hours numeric(6,2) default 0
);
create index if not exists attendance_user_open_idx on attendance(user_id,check_out);

create table if not exists discussion_templates (
  template_id bigint generated by default as identity primary key,
  template_name text not null, university_name text, college_name text,
  university_logo_url text, college_logo_url text, background_url text,
  is_default boolean not null default false, created_at timestamptz not null default now()
);

create table if not exists settings (
  setting_key text primary key, setting_value jsonb not null, updated_at timestamptz not null default now()
);

create table if not exists financial_entries (
  entry_id bigint generated by default as identity primary key, entry_date date not null default current_date,
  entry_type text not null check(entry_type in ('INCOME','EXPENSE')),
  category text not null check(category in ('SALES','SALARY','RENT','ELECTRICITY','POS_COMMISSION','SUPPLIES','OTHER')),
  description text, amount numeric(14,2) not null check(amount>=0),
  payment_method text not null default 'CASH' check(payment_method in ('CASH','GREEN_CARD','BLACK_CARD','BANK')),
  created_by bigint references users(user_id) on delete set null,
  spent_by text,
  entry_source text not null default 'MANUAL',
  created_at timestamptz not null default now()
);
create table if not exists pos_transactions (
  pos_id bigint generated by default as identity primary key, transaction_date date not null default current_date,
  card_type text not null check(card_type in ('GREEN_CARD','BLACK_CARD')),
  direction text not null default 'IN' check(direction in ('IN','OUT')),
  transfer_amount numeric(14,2) not null check(transfer_amount>=0), commission numeric(14,2) not null default 0 check(commission>=0),
  notes text, created_by bigint references users(user_id) on delete set null, created_at timestamptz not null default now()
);
create table if not exists partners (
  partner_id bigint generated by default as identity primary key, partner_name text not null,
  share_percent numeric(5,2) not null check(share_percent>0 and share_percent<=100),
  is_active boolean not null default true, created_at timestamptz not null default now()
);

create table if not exists partner_payments (
  payment_id bigint generated by default as identity primary key,
  partner_id bigint not null references partners(partner_id) on delete cascade,
  payment_date date not null default current_date,
  amount numeric(14,2) not null check(amount>0),
  payment_method text not null default 'CASH' check(payment_method in ('CASH','GREEN_CARD','BLACK_CARD','BANK')),
  notes text, created_by bigint references users(user_id) on delete set null, created_at timestamptz not null default now()
);
create table if not exists pos_daily_closings (
  closing_id bigint generated by default as identity primary key, closing_date date not null unique,
  cash_amount numeric(14,2) not null default 0, green_card_amount numeric(14,2) not null default 0,
  black_card_amount numeric(14,2) not null default 0, notes text,
  created_by bigint references users(user_id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists notifications (
  notification_id bigint generated by default as identity primary key,
  audience text not null check(audience in ('ALL','STUDENTS','STAFF')), message text not null,
  is_active boolean not null default true, starts_at timestamptz not null default now(), ends_at timestamptz,
  created_by bigint references users(user_id) on delete set null, created_at timestamptz not null default now()
);
create table if not exists chat_conversations (
  conversation_id bigint generated by default as identity primary key, public_token uuid not null default gen_random_uuid() unique,
  student_name text not null, phone text not null, status text not null default 'OPEN' check(status in ('OPEN','CLOSED')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists chat_messages (
  message_id bigint generated by default as identity primary key,
  conversation_id bigint not null references chat_conversations(conversation_id) on delete cascade,
  sender_type text not null check(sender_type in ('STUDENT','STAFF')),
  sender_user_id bigint references users(user_id) on delete set null, message_text text,
  attachment_name text, attachment_path text, attachment_storage_path text, created_at timestamptz not null default now()
);
