create table if not exists stages (
  stage_id bigint generated by default as identity primary key,
  code text unique not null,
  name text unique not null,
  sort_order integer not null default 0,
  is_active boolean not null default true
);
insert into stages(code,name,sort_order) values
('1','المرحلة الأولى',1),('2','المرحلة الثانية',2),('3','المرحلة الثالثة',3),
('4','المرحلة الرابعة',4),('masters','الماجستير',5),('phd','الدكتوراه',6)
on conflict(code) do update set name=excluded.name, sort_order=excluded.sort_order;

create table if not exists study_materials (
  material_id bigint generated by default as identity primary key,
  department_code text not null references departments(code) on update cascade,
  stage_code text not null references stages(code) on update cascade,
  subject_name text not null,
  title text not null,
  doctor_name text,
  file_path text not null,
  storage_path text,
  uploaded_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists student_print_files (
  file_id bigint generated by default as identity primary key,
  original_name text not null,
  file_path text not null,
  storage_path text,
  copies integer not null default 1 check(copies between 1 and 100),
  color_mode text not null default 'BW' check(color_mode in ('BW','COLOR')),
  status text not null default 'QUEUED' check(status in ('QUEUED','PRINTING','COMPLETED','CANCELLED')),
  completed_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table student_print_files add column if not exists student_name text;
alter table student_print_files add column if not exists phone text;
alter table student_print_files add column if not exists notes text;

create table if not exists tasks (
  task_id bigint generated by default as identity primary key,
  task_type text not null default 'عام', title text not null, description text,
  assigned_to bigint references users(user_id) on delete set null,
  completed_by bigint references users(user_id) on delete set null,
  status text not null default 'PENDING' check(status in ('PENDING','IN_PROGRESS','COMPLETED','CANCELLED')),
  expected_completion_at timestamptz, created_at timestamptz not null default now(), completed_at timestamptz
);

create table if not exists discussions (
  discussion_id bigint generated by default as identity primary key,
  gender text not null check(gender in ('MALE','FEMALE')),
  degree_type text not null check(degree_type in ('MASTER','DOCTORATE')),
  student_name text not null, thesis_title text not null,
  discussion_date text not null, location_hall text not null,
  university_name text, college_name text, template_path text,
  created_by bigint references users(user_id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists discussion_committee (
  committee_id bigint generated by default as identity primary key,
  discussion_id bigint not null references discussions(discussion_id) on delete cascade,
  member_name text not null, academic_title text, workplace text,
  role_in_committee text not null, member_order integer not null
);

create table if not exists attendance (
  attendance_id bigint generated by default as identity primary key,
  user_id bigint not null references users(user_id) on delete cascade,
  check_in timestamptz not null default now(), check_out timestamptz,
  regular_hours numeric(6,2) default 0, overtime_hours numeric(6,2) default 0
);

create table if not exists discussion_templates (
  template_id bigint generated by default as identity primary key,
  template_name text not null, university_name text, college_name text,
  university_logo_url text, college_logo_url text, background_url text,
  is_default boolean not null default false, created_at timestamptz not null default now()
);

create table if not exists settings (
  setting_key text primary key, setting_value jsonb not null, updated_at timestamptz not null default now()
);

alter table users enable row level security;
alter table study_materials enable row level security;
alter table student_print_files enable row level security;
alter table tasks enable row level security;
alter table discussions enable row level security;
